// Internal, lazy-loaded capture for the standalone reader.
(function (root) {
  'use strict';

  var DF = root.DocForm;
  var document = root.document;
  var chrome = '.df-sidebar,.df-nav-toggle,.df-controls,.df-controls-bar,.df-heading-link,' +
    '.df-pager,.df-section-lines,.df-section-rail,.df-search,.df-zoom,[data-df-reader-state-control],[data-df-export-control]';
  var transient = '.df-tooltip,.df-chart-tip,.df-chart-hover,.df-chart-x-cursor,.df-chart-brush,.df-step-indicator,' +
    '.df-step-label-bold,.df-code-copy,.df-step-search,.df-tree-bar,.df-tree-twisty,.df-choices-glider,' +
    '.df-dropzone-hint,.df-dropzone-prompt,' +
    '.df-pill-button,.df-anim-scrub,.df-chart-reset,.df-chart-toggle,.df-filter-toggle,.df-filter-clear,' +
    '.df-tree-diagram-toggle,.df-glossary-clear,.df-dropzone input,.df-dropzone button,.df-data-more button';
  var embeds = 'iframe,frame,object,embed,portal,fencedframe';
  var declarative = 'script:not([src])[type="application/json"],script:not([src])[data-df-source],' +
    'script:not([src])[type="text/csv"],script:not([src])[type="text/json"],' +
    'script:not([src])[type="text/yaml"],script:not([src])[type="application/yaml"]';

  function sameURL(a, b) {
    if (!a || !b) return false;
    try {
      var first = new URL(a);
      var second = new URL(b);
      first.hash = second.hash = first.search = second.search = '';
      return first.href === second.href;
    } catch (error) { return false; }
  }

  function wrappedAsset(kind, name, source) {
    var text = source.replace(/^\s*\/\/ Generated by DocForm tools\/assets\.html\.[^\S\r\n]*\r?\n/, '').trim();
    if (kind === 'search') {
      var search = /^window\.DocFormSearch\s*=\s*([\s\S]+);$/.exec(text);
      if (search) return JSON.parse(search[1]);
    } else {
      var data = /^Object\.defineProperty\(window\.DocFormData \|\| \(window\.DocFormData = Object\.create\(null\)\), ("(?:[^"\\]|\\.)*"), \{ configurable: true, enumerable: true, writable: true, value: ([\s\S]+) \}\);$/.exec(text);
      if (data && JSON.parse(data[1]) === name) return JSON.parse(data[2]);
    }
    throw new Error('Unsupported DocForm asset wrapper.');
  }

  function issue(issues, code, node, message) {
    issues.push({ code: code, target: node?.id || node?.getAttribute('src') || node?.localName || null, message: message });
  }

  function fallback(node, issues, code) {
    var label = node.getAttribute('aria-label') || node.getAttribute('title') || node.getAttribute('alt');
    var replacement = node.ownerDocument.createElement('div');
    if (node.id) replacement.id = node.id;
    if (node.matches('object,canvas')) replacement.append(...node.childNodes);
    if (!replacement.textContent.trim() && !replacement.querySelector('img,svg')) {
      replacement.append(label || 'Embedded content is unavailable in this snapshot.');
    }
    issue(issues, code, node, 'Embedded content uses a static fallback.');
    node.replaceWith(replacement);
  }

  function showStaticFallbacks(scope) {
    scope.querySelectorAll('noscript').forEach(function (node) {
      var owner = node.ownerDocument;
      var content = owner.createElement('div');
      if (node.children.length) content.append(...node.childNodes);
      else {
        var template = owner.createElement('template');
        template.innerHTML = node.textContent;
        content.append(template.content);
      }
      if (node.id) content.id = node.id;
      node.replaceWith(content);
    });
  }

  function neutralize(scope) {
    var nodes = Array.from(scope.querySelectorAll('*'));
    if (scope.nodeType === 1) nodes.unshift(scope);
    nodes.forEach(function (node) {
      Array.from(node.attributes).forEach(function (attr) {
        if (/^on/i.test(attr.name) || ['autofocus', 'autoplay', 'ping'].includes(attr.name) ||
            /^(?:href|xlink:href|src|action|formaction)$/i.test(attr.name) &&
            /^\s*javascript:/i.test(attr.value.replace(/[\t\r\n]/g, ''))) {
          node.removeAttribute(attr.name);
        }
      });
    });
  }

  function staticControl(node, document, original) {
    original = original || node;
    var tag = node.localName;
    var copy = document.createElement(tag === 'textarea' ? 'pre' : 'span');
    Array.from(node.attributes).forEach(function (attr) {
      if (/^(?:id|class|style|title|aria-describedby|aria-label|data-df-.+)$/.test(attr.name)) {
        copy.setAttribute(attr.name, attr.value);
      }
    });
    if (tag === 'button') {
      copy.append(...node.childNodes);
      if (node.getAttribute('aria-selected') === 'true' || node.getAttribute('aria-pressed') === 'true') {
        copy.setAttribute('data-df-snapshot-selected', '');
      }
      if (node.hasAttribute('aria-current')) copy.setAttribute('aria-current', node.getAttribute('aria-current'));
    } else if (tag === 'select') {
      copy.textContent = Array.from(original.selectedOptions, function (option) { return option.label; }).join(', ');
    } else if (node.type === 'checkbox' || node.type === 'radio') {
      if (!node.closest('.df-chip')) {
        copy.textContent = (original.checked ? '☑' : '☐') + ' ' + (node.getAttribute('aria-label') || '');
      }
    } else if (['file', 'password', 'hidden'].includes(node.type)) {
      node.remove();
      return;
    } else {
      copy.textContent = node.closest('.df-param') ? original.value : original.defaultValue;
    }
    if (copy.childNodes.length) node.replaceWith(copy);
    else node.remove();
  }

  function stylesheetRecords(document) {
    var nodes = document.querySelectorAll('style,link[rel~="stylesheet"][href]:not([disabled],[data-df-export-control])');
    return Array.from(nodes, function (node) {
      return { href: node.localName === 'link' ? node.href : null, text: node.localName === 'style' ? node.textContent : null,
        media: node.media || '' };
    });
  }

  // The packager can scope these rules with the page and run its own tooltip reader.
  var style = '[data-df-snapshot] *,[data-df-snapshot] *::before,[data-df-snapshot] *::after{' +
    'animation:none!important;transition:none!important}' +
    '[data-df-snapshot] [hidden]{display:none!important}' +
    '[data-df-snapshot] [data-df-snapshot-selected]{font-weight:700}' +
    '[data-df-snapshot] .df-chip.is-selected{background:var(--df-accent-bg,var(--df-bg-hover))!important}' +
    '[data-df-snapshot] .df-sidenote{display:inline!important;float:none!important;position:static!important;' +
    'width:auto!important;margin:0!important;padding:0!important}' +
    '[data-df-snapshot] .df-sidenote::before{content:" ("}' +
    '[data-df-snapshot] .df-sidenote::after{content:")"}' +
    '[data-df-snapshot] .df-detail-pane,[data-df-snapshot] .df-step-details,' +
    '[data-df-snapshot] .df-detail-pane>*,[data-df-snapshot] .df-step-details>*{' +
    'max-block-size:none!important;overflow:visible!important}' +
    '[data-df-snapshot] [data-df-snapshot-bubble]>.df-bubble-sheet{max-height:none!important}' +
    '[data-df-snapshot] [data-df-snapshot-bubble] .df-bubble-body{filter:none!important;opacity:1!important}';

  function freeze(view, status, issues, imports) {
    var source = view.document;
    var runtime = view.DocForm;
    var output = document.implementation.createHTMLDocument('');
    var body = output.importNode(source.body, true);
    var originals = [source.body].concat(Array.from(source.body.querySelectorAll('*')));
    var copies = [body].concat(Array.from(body.querySelectorAll('*')));
    var mapped = new Map(originals.map(function (node, index) { return [node, copies[index]]; }));
    var originalControls = new Map();
    var tips = output.createElement('div');
    tips.hidden = true;
    tips.setAttribute('data-df-snapshot-tips', '');
    var tipIDs = new Set();
    body.setAttribute('data-df-snapshot', '');

    var zoom = runtime?._zoom?.snapshotPlacement();
    if (zoom) {
      var figure = mapped.get(zoom.target);
      if (figure) {
        figure.classList.remove('df-zoomed');
        mapped.get(zoom.placeholder)?.replaceWith(figure);
      }
    }
    originals.forEach(function (node) {
      var copy = mapped.get(node);
      if (copy.matches('input,textarea,select')) originalControls.set(copy, node);
      if (copy.classList.contains('df-bubble')) {
        var sheet = mapped.get(source.getElementById(node.getAttribute('aria-controls')));
        if (sheet) copy.appendChild(sheet);
        copy.classList.add('is-open', 'is-revealed');
        copy.setAttribute('data-df-snapshot-bubble', '');
        copy.removeAttribute('role');
        copy.removeAttribute('aria-expanded');
        copy.removeAttribute('aria-controls');
      }
    });
    body.querySelectorAll(chrome + ',' + transient + ',.df-bubble-store,[hidden],[inert],[data-df-pipe-hidden],.df-tree-diagram-folded')
      .forEach(function (node) { node.remove(); });
    body.querySelectorAll('.df-show-leave').forEach(function (node) { node.remove(); });
    body.querySelectorAll('.df-show-enter,.df-callout-away,.df-chart-await,.df-pipe-tracing,.df-focus-dim,.df-ref-flash')
      .forEach(function (node) {
        node.classList.remove('df-show-enter', 'df-callout-away', 'df-chart-await', 'df-pipe-tracing', 'df-focus-dim', 'df-ref-flash');
      });

    originals.forEach(function (node) {
      var copy = mapped.get(node);
      if (!body.contains(copy)) return;
      if (copy.classList.contains('df-chart')) {
        var frame = runtime?._chart?.snapshotFrame(node);
        if (frame) copy.querySelector('.df-chart-plot > svg')?.replaceWith(output.importNode(frame, true));
      }
      if (copy.localName.includes('-') && copy.namespaceURI === 'http://www.w3.org/1999/xhtml') {
        issue(issues, 'custom-element', node, 'Custom content uses its available static markup.');
        if (!copy.textContent.trim() && !copy.children.length) copy.textContent = 'Custom content is unavailable in this snapshot.';
      }
      if (copy.classList.contains('df-note-mark')) {
        var ref = output.createElement('a');
        ref.href = '#' + copy.getAttribute('aria-controls');
        ref.textContent = copy.textContent;
        ref.setAttribute('aria-label', copy.getAttribute('aria-label') || 'Note');
        copy.replaceWith(ref);
        return;
      }
      var cards;
      try { cards = runtime?._tooltips?.snapshot(node, output); }
      catch (error) {
        issue(issues, 'tooltip', node, 'A tooltip could not be rendered.');
        return;
      }
      if (!cards?.length) return;
      copy.setAttribute('data-df-snapshot-tip', cards.map(function (card) { return card.id; }).join(' '));
      cards.forEach(function (card) {
        if (tipIDs.has(card.id)) return;
        tipIDs.add(card.id);
        tips.appendChild(card);
      });
    });

    body.appendChild(tips);
    showStaticFallbacks(body);
    body.querySelectorAll('script,style,link,base,meta,template,.df-tooltip-ring,.df-filter-menu,[role="listbox"]')
      .forEach(function (node) { node.remove(); });
    body.querySelectorAll('canvas,' + embeds).forEach(function (node) { fallback(node, issues, 'unsupported-embed'); });
    body.querySelectorAll('animate,animateMotion,animateTransform,set').forEach(function (node) {
      issue(issues, 'unsupported-animation', node, 'SVG animation uses its authored static drawing.');
      node.remove();
    });
    body.querySelectorAll('.df-dropdown-panel[popover]').forEach(function (node) {
      node.removeAttribute('popover');
      node.removeAttribute('style');
    });
    body.querySelectorAll('button,input,textarea,select').forEach(function (node) {
      staticControl(node, output, originalControls.get(node));
    });
    body.querySelectorAll('[tabindex],[contenteditable],[aria-live],[data-df-pipe-trace],[popover],[popovertarget],' +
      '[role="tab"],[role="tabpanel"],[role="tablist"],[role="button"],[data-df-snapshot-tip]').forEach(function (node) {
      ['tabindex', 'contenteditable', 'aria-live', 'data-df-pipe-trace', 'popover', 'popovertarget'].forEach(function (attr) {
        node.removeAttribute(attr);
      });
      if (node.hasAttribute('data-df-snapshot-tip') && !node.matches('a[href]')) node.tabIndex = 0;
      if (['tab', 'tabpanel', 'tablist', 'button'].includes(node.getAttribute('role'))) node.removeAttribute('role');
    });
    neutralize(body);

    output.body.replaceWith(body);
    return { url: runtime?._page || view.location.href, baseURL: source.baseURI, title: source.title,
      htmlAttributes: Array.from(source.documentElement.attributes, function (attr) {
        var value = attr.value;
        if (attr.name === 'class') {
          value = value.split(/\s+/).filter(function (name) {
            return !/^df-(?:focus-mode|sidenotes|zoom-open|nav-|has-controls|reveal-on)/.test(name);
          }).join(' ');
        }
        return [attr.name, value];
      }).filter(function ([name]) { return name !== 'data-df-export-replay' && !/^on/i.test(name); }),
      body: body, styles: stylesheetRecords(source).concat({ href: null, text: style, media: '' }),
      view: status, imports: imports, issues: issues };
  }

  function importSummary(saved, replay) {
    return (replay?.status === 'stale' ? [] : saved.record?.imports || []).filter(function ([key]) {
      return !replay?.issues.some(function (item) { return item.kind === 'import' && item.key === key; });
    }).map(function ([key, item]) { return { target: key, name: item.name, type: item.type }; });
  }

  function scriptIssues(source, library, siteURL, issues) {
    source.querySelectorAll('script').forEach(function (node) {
      var src = node.getAttribute('src');
      if (node.matches(declarative + ',[data-df-runtime-asset]') ||
          (src && (node.hasAttribute('data-df-site') && sameURL(node.src, siteURL) ||
          sameURL(node.src, library) || /(?:^|\/)docform\.js$/.test(src) && node.closest('head')))) return;
      issue(issues, 'custom-script', node, 'Author-script behavior uses the available static markup.');
    });
  }

  function waitFor(signal, run) {
    return new Promise(function (resolve, reject) {
      if (signal?.aborted) return reject(signal.reason);
      var timer = root.setTimeout(function () { finish(new Error('The page renderer did not finish.')); }, 20000);
      function cancel() { finish(signal.reason || new Error('Page capture was cancelled.')); }
      function finish(error, result) {
        root.clearTimeout(timer);
        signal?.removeEventListener('abort', cancel);
        if (error) reject(error);
        else resolve(result);
      }
      signal?.addEventListener('abort', cancel, { once: true });
      try { run(finish); } catch (error) { finish(error); }
    });
  }

  function copyAttributes(from, to) {
    Array.from(from.attributes).forEach(function (attr) { to.setAttribute(attr.name, attr.value); });
  }

  async function replayPage(page, saved, signal) {
    var nonce = Array.from(root.crypto.getRandomValues(new Uint8Array(24)), function (byte) {
      return byte.toString(16).padStart(2, '0');
    }).join('');
    var frame = document.createElement('iframe');
    frame.setAttribute('sandbox', 'allow-scripts allow-same-origin');
    frame.setAttribute('aria-hidden', 'true');
    frame.inert = true;
    frame.style.cssText = 'position:fixed;inset:0;width:' + root.innerWidth +
      'px;height:' + root.innerHeight + 'px;border:0;opacity:0;pointer-events:none;z-index:-1';
    frame.srcdoc = '<!doctype html><meta http-equiv="Content-Security-Policy" content="' +
      "default-src 'none'; script-src 'nonce-" + nonce + "'; style-src 'unsafe-inline' file: blob: data:; " +
      'img-src file: blob: data:; font-src file: blob: data:; media-src file: blob: data:; form-action \'none\'">';
    var issues = [];
    try {
      var view = await waitFor(signal, function (finish) {
        frame.onload = function () { finish(null, frame.contentWindow); };
        document.body.appendChild(frame);
      });
      var target = view.document;
      var source = new view.DOMParser().parseFromString(page.html, 'text/html');
      var library = DF._boot.entryURL;
      var base = target.createElement('base');
      base.href = new URL(source.querySelector('base[href]')?.getAttribute('href') || page.url, page.url).href;
      target.head.appendChild(base);
      // The parsed document has no source URL. Resolve authored paths against the selected page.
      var sourceBase = source.createElement('base');
      sourceBase.href = base.href;
      source.head.prepend(sourceBase);
      var siteNode = source.querySelector('script[data-df-site]');
      var siteURL = page.siteURL || (siteNode?.hasAttribute('src') ? siteNode.src : page.url);
      scriptIssues(source, library, siteURL, issues);
      var settings = source.querySelector('head script[src$="docform.js"],body script[src$="docform.js"]');
      showStaticFallbacks(source.body);
      source.querySelectorAll('script,base,meta[http-equiv],link:not([rel~="stylesheet"]),' + embeds).forEach(function (node) {
        if (node.matches(embeds)) fallback(node, issues, 'unsupported-embed');
        else if (!node.matches(declarative)) node.remove();
      });
      source.querySelectorAll('script[nonce]').forEach(function (node) { node.removeAttribute('nonce'); });
      neutralize(source);
      copyAttributes(source.documentElement, target.documentElement);
      copyAttributes(source.body, target.body);
      target.documentElement.setAttribute('data-df-export-replay', '');
      target.head.append(...Array.from(source.head.childNodes, function (node) { return target.importNode(node, true); }));
      target.body.append(...Array.from(source.body.childNodes, function (node) { return target.importNode(node, true); }));
      if (page.site) {
        var manifest = target.createElement('script');
        manifest.type = 'application/json';
        manifest.setAttribute('data-df-site', '');
        target.head.appendChild(manifest);
        view.DocFormSite = page.site;
      } else if (siteNode) {
        issue(issues, 'missing-manifest', siteNode, 'The page was rendered with its page configuration and default site settings.');
      }

      view.DocFormExportContext = {
        pageURL: page.url, siteURL: siteURL,
        loadAsset: async function (kind, url, name) {
          try {
            var sourceText = await page.readText?.(url);
            var value = wrappedAsset(kind, name, sourceText);
            if (!value || typeof value !== 'object') return false;
            if (kind === 'search') view.DocFormSearch = value;
            else (view.DocFormData ||= Object.create(null))[name] = value;
            return true;
          } catch (error) { return false; }
        }
      };
      var runtime = await waitFor(signal, function (finish) {
        var entry = target.createElement('script');
        if (settings?.hasAttribute('data-df-profile')) entry.setAttribute('data-df-profile', settings.getAttribute('data-df-profile'));
        entry.nonce = nonce;
        entry.onload = function () { view.DocForm.ready(function (runtime) { finish(null, runtime); }); };
        entry.onerror = function () { finish(new Error('The trusted DocForm library could not load in the page renderer.')); };
        entry.src = library;
        target.head.appendChild(entry);
      });
      if (!runtime._site || !runtime._readerState) throw new Error('DocForm did not initialize in the page renderer.');
      var replay = runtime._readerState.replay(saved);
      // Glossary rebuilding and cross-page preview text can wait on the wrapped search index.
      if (runtime._search?.load) await waitFor(signal, function (finish) {
        runtime._search.load(function () { finish(); });
      });
      // Resize observers redraw views that were hidden until saved selections were applied.
      await waitFor(signal, function (finish) {
        var fallback = view.setTimeout(finish, 150);
        view.requestAnimationFrame(function () {
          view.requestAnimationFrame(function () {
            view.clearTimeout(fallback);
            finish();
          });
        });
      });
      runtime.diagnostics.list().forEach(function (item) {
        issue(issues, item.code, item.target?.nodeType ? item.target : null, item.message);
      });
      replay.issues.forEach(function (item) {
        issues.push({ code: 'saved-' + item.kind, target: item.key, message: item.reason });
      });
      var status = replay.status === 'missing' ? 'default' : replay.status;
      if (status !== 'default' && status !== 'saved' && status !== 'live') {
        issues.push({ code: 'saved-page', target: page.url, message: 'Saved view status: ' + status + '.' });
      }
      return freeze(view, status, issues, importSummary(saved, replay));
    } finally {
      frame.remove();
    }
  }

  async function capture(page, options) {
    var signal = options?.signal;
    signal?.throwIfAborted();
    var state = DF._readerState;
    if (!state) throw new Error('The open page has no initialized reader state.');
    var live = !page || sameURL(page.url, DF._page);
    if (live && DF._search?.load) await waitFor(signal, function (finish) {
      DF._search.load(function () { finish(); });
    });
    var saved = live ? state.capture() : await state.read(page.url);
    signal?.throwIfAborted();
    if (!live && typeof page.html !== 'string') throw new Error('Page replay needs the selected page HTML.');
    if (!live || saved.preview) {
      if (typeof page?.html !== 'string') throw new Error('Restoring the committed view needs the selected page HTML.');
      return replayPage(page, saved, signal);
    }
    var issues = [];
    scriptIssues(document, DF._boot.entryURL, document.querySelector('script[data-df-site]')?.src, issues);
    return freeze(root, 'live', issues, importSummary(saved));
  }

  DF._pageSnapshot = { capture: capture };
})(typeof window !== 'undefined' ? window : globalThis);
