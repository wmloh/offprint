"""Check or refresh a DocForm site's generated assets: data wrappers in Python, and the search index through the
Node command-line builder beside this file."""

import csv
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import unquote
import xml.etree.ElementTree as ElementTree


HEADER = '// Generated by DocForm tools/assets.html.\n'
SEARCH_CLI = Path(__file__).resolve().with_name('refresh-assets.js')
TYPES = ('csv', 'tsv', 'json', 'yaml', 'xml', 'markdown')
ALIASES = {
    'yml': 'yaml', 'md': 'markdown', 'text/csv': 'csv', 'text/tab-separated-values': 'tsv',
    'application/json': 'json', 'text/json': 'json', 'text/yaml': 'yaml', 'application/yaml': 'yaml',
    'text/x-yaml': 'yaml', 'application/x-yaml': 'yaml', 'application/xml': 'xml', 'text/xml': 'xml',
    'text/markdown': 'markdown', 'text/x-markdown': 'markdown',
}


def object_value(value, label):
    if not isinstance(value, dict):
        raise ValueError(f'{label} must be a JSON object')
    return value


def local_path(value, base, root):
    if not isinstance(value, str):
        raise ValueError('Specify a path relative to the manifest')
    value = value.strip()
    if not value or re.match(r'[/\\]|[a-z][a-z\d+.-]*:', value, re.I) or re.search(r'[\\?#]', value):
        raise ValueError(f'Invalid relative file path: {value!r}')
    segments = [unquote(part, errors='strict') for part in value.split('/')]
    if segments[-1] in ('', '.', '..') or any(re.search(r'[/\\\x00-\x1f]', part) for part in segments):
        raise ValueError(f'Invalid relative file path: {value!r}')
    path = base.joinpath(*segments).resolve()
    if not path.is_relative_to(root):
        raise ValueError(f'Path leaves the site folder: {value!r}')
    return path


def invalid_constant(value):
    raise ValueError(f'Invalid JSON constant: {value}')


def validate_yaml(text):
    try:
        import yaml
    except ImportError:
        raise ValueError('YAML sources need PyYAML; install it with: python3 -m pip install pyyaml') from None
    loader = getattr(yaml, 'CSafeLoader', yaml.SafeLoader)
    try:
        documents = list(yaml.load_all(text, Loader=loader))
    except yaml.YAMLError as error:
        raise ValueError(f'Invalid YAML: {error}') from None
    if len(documents) > 1:
        raise ValueError(f'Found {len(documents)} YAML documents; a data source reads one')


def validate_xml(text):
    if re.search(r'<!(?!--|\[CDATA\[)', text):
        raise ValueError('XML DOCTYPE and other declarations are not supported')
    try:
        ElementTree.fromstring(text)
    except ElementTree.ParseError as error:
        raise ValueError(f'Invalid XML: {error}') from None


def validate(text, kind):
    if kind == 'json':
        json.loads(text, parse_constant=invalid_constant)
    elif kind == 'yaml':
        validate_yaml(text)
    elif kind == 'xml':
        validate_xml(text)
    elif kind in ('csv', 'tsv'):
        label = kind.upper()
        csv.field_size_limit(2**31 - 1)
        reader = csv.reader(io.StringIO(text, newline=''), delimiter='\t' if kind == 'tsv' else ',', strict=True)
        rows = (row for row in reader if row)
        header = next(rows, None)
        if header is None:
            raise ValueError(f'The {label} is empty')
        for row in rows:
            if len(row) != len(header):
                raise ValueError(f'A {label} row has a different number of fields than the header')


def wrapper(name, source, target, kind, root, prefix):
    raw = source.read_bytes()
    text = raw.decode('utf-8-sig')
    validate(text, kind)
    payload = {
        'format': 'docform-data',
        'version': 1,
        'metadata': {
            'generator': 1,
            'output': target.relative_to(root).as_posix(),
            'config': {'name': name, 'type': kind},
            'inputs': [{'file': source.relative_to(root).as_posix(), 'sha256': hashlib.sha256(raw).hexdigest()}],
        },
        'type': kind,
        'text': text,
    }
    return (prefix + json.dumps(payload, ensure_ascii=False, indent=2) + ' });\n').encode('utf-8')


def read_site(manifest):
    assignment = re.fullmatch(r'\s*window\.DocFormSite\s*=\s*(.*?)\s*;\s*',
                              manifest.read_text(encoding='utf-8-sig'), re.DOTALL)
    if not assignment:
        raise ValueError('Use window.DocFormSite = <JSON object>; in the manifest')
    return object_value(json.loads(assignment[1], parse_constant=invalid_constant), 'Manifest')


def changes(site, manifest, root):
    assets = object_value(site.get('assets', {}), 'assets')
    datasets = object_value(assets.get('data', {}), 'assets.data')

    sources = {manifest}
    outputs = set()
    if 'search' in assets:
        search = object_value(assets['search'], 'assets.search')
        outputs.add(local_path(search.get('output'), manifest.parent, root))
    jobs = []
    for name, config in datasets.items():
        if not name or name != name.strip():
            raise ValueError('Use a nonempty, trimmed source name')
        config = object_value(config, name)
        source = local_path(config.get('source'), manifest.parent, root)
        target = local_path(config.get('output'), manifest.parent, root)
        if target in outputs:
            raise ValueError(f'Multiple assets use the output {target}')
        sources.add(source)
        outputs.add(target)
        kind = str(config.get('type', source.suffix[1:])).strip().lower()
        jobs.append((name, source, target, ALIASES.get(kind, kind)))

    for name, source, target, kind in jobs:
        if kind not in TYPES:
            raise ValueError(f'{name}: set type to one of {", ".join(TYPES)}, or use a matching source extension')
        if target in sources or target.suffix.lower() != '.js':
            raise ValueError(f'{name}: use a separate .js output path')
        prefix = (HEADER + 'Object.defineProperty(window.DocFormData || (window.DocFormData = Object.create(null)), '
                  + json.dumps(name, ensure_ascii=False) + ', { configurable: true, enumerable: true, writable: true, value: ')
        existing = target.read_bytes() if target.exists() else None
        if existing is not None and not existing.startswith(prefix.encode('utf-8')):
            raise ValueError(f'{name}: output is not a generated wrapper for this dataset: {target}')
        try:
            data = wrapper(name, source, target, kind, root, prefix)
        except (OSError, ValueError, csv.Error) as error:
            raise ValueError(f'{name} ({source}): {error}') from error
        yield target, data, existing


def replace(target, data):
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as pending:
        staged = Path(pending.name)
        try:
            pending.write(data)
            pending.close()
            os.replace(staged, target)
        finally:
            staged.unlink(missing_ok=True)


def search_index(manifest, root, check, node):
    """Runs the Node builder for the search index; returns 'ok', 'failed' (stale or blocked), or 'skipped'."""
    node = node or os.environ.get('DOCFORM_NODE') or shutil.which('node')
    if not node:
        print('Skipped: search index. Node.js was not found; install it, set DOCFORM_NODE, '
              'or refresh the index with docform/tools/assets.html.', file=sys.stderr)
        return 'skipped'
    command = [node, str(SEARCH_CLI), str(root), '--manifest=' + manifest.relative_to(root).as_posix(), '--search']
    try:
        sys.stdout.flush()
        code = subprocess.run(command + (['--check'] if check else []), check=False).returncode
    except OSError as error:
        print(f'Skipped: search index. Cannot run {node}: {error}', file=sys.stderr)
        return 'skipped'
    return 'ok' if code == 0 else 'failed'


def refresh(manifest, *, site_root=None, check=False, node=None):
    """Checks every manifest asset, then writes stale data wrappers and the search index unless `check` is set.

    Nothing is written when a data source is invalid or the search index is blocked. Without Node.js, data wrappers
    still refresh and the search index is reported as skipped. Returns a process exit code: 0 when every asset is
    current or was refreshed.
    """
    try:
        manifest = Path(manifest).resolve()
        root = Path(site_root).resolve() if site_root is not None else manifest.parent
        if not manifest.is_relative_to(root):
            raise ValueError('The manifest must be inside the site folder')
        site = read_site(manifest)
        updates = list(changes(site, manifest, root))
        assets = object_value(site.get('assets', {}), 'assets')
        search = search_index(manifest, root, check, node) if 'search' in assets else 'ok'
        if search == 'failed' and not check:
            print('No data wrappers were written because the search index is blocked.', file=sys.stderr)
            return 1
        stale = False
        for target, data, existing in updates:
            name = target.relative_to(root)
            if data == existing:
                print(f'Current: {name}')
            elif check:
                stale = True
                print(f'{"Missing" if existing is None else "Stale"}: {name}')
            else:
                replace(target, data)
                print(f'Updated: {name}')
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0 if search == 'ok' and not stale else 1


def main(manifest, *, site_root=None, argv=None):
    """Entry point for project launchers: accepts only an optional --check argument."""
    args = sys.argv[1:] if argv is None else list(argv)
    if any(arg != '--check' for arg in args):
        print('Usage: refresh-assets.py [--check]', file=sys.stderr)
        return 2
    return refresh(manifest, site_root=site_root, check='--check' in args)
