"""Refresh offline DocForm data wrappers from a project manifest."""

import csv
import hashlib
import io
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from urllib.parse import unquote


HEADER = '// Generated by DocForm tools/assets.html.\n'
MIMES = {'text/csv': 'csv', 'application/json': 'json', 'text/json': 'json'}


def object_value(value, label):
    if not isinstance(value, dict):
        raise ValueError(f'{label} must be a JSON object')
    return value


def local_path(value, base, root):
    if not isinstance(value, str):
        raise ValueError('Specify a path relative to the manifest')
    value = value.strip()
    if not value or re.match(r'[/\\]|[a-z][a-z\d+.-]*:', value, re.I) or re.search(r'[\\?#]', value):
        raise ValueError(f'Invalid relative file path: {value!r}')
    segments = [unquote(part, errors='strict') for part in value.split('/')]
    if segments[-1] in ('', '.', '..') or any(re.search(r'[/\\\x00-\x1f]', part) for part in segments):
        raise ValueError(f'Invalid relative file path: {value!r}')
    path = base.joinpath(*segments).resolve()
    if not path.is_relative_to(root):
        raise ValueError(f'Path leaves the site folder: {value!r}')
    return path


def invalid_constant(value):
    raise ValueError(f'Invalid JSON constant: {value}')


def validate(text, kind):
    if kind == 'json':
        json.loads(text, parse_constant=invalid_constant)
        return
    csv.field_size_limit(2**31 - 1)
    rows = (row for row in csv.reader(io.StringIO(text, newline=''), strict=True) if row)
    header = next(rows, None)
    if header is None:
        raise ValueError('The CSV is empty')
    for row in rows:
        if len(row) != len(header):
            raise ValueError('A CSV row has a different number of fields than the header')


def wrapper(name, source, target, kind, root, prefix):
    raw = source.read_bytes()
    text = raw.decode('utf-8-sig')
    validate(text, kind)
    payload = {
        'format': 'docform-data',
        'version': 1,
        'metadata': {
            'generator': 1,
            'output': target.relative_to(root).as_posix(),
            'config': {'name': name, 'type': kind},
            'inputs': [{'file': source.relative_to(root).as_posix(), 'sha256': hashlib.sha256(raw).hexdigest()}],
        },
        'type': kind,
        'text': text,
    }
    return (prefix + json.dumps(payload, ensure_ascii=False, indent=2) + ' });\n').encode('utf-8')


def changes(manifest, root):
    assignment = re.fullmatch(r'\s*window\.DocFormSite\s*=\s*(.*?)\s*;\s*',
                              manifest.read_text(encoding='utf-8-sig'), re.DOTALL)
    if not assignment:
        raise ValueError('Use window.DocFormSite = <JSON object>; in the manifest')
    site = object_value(json.loads(assignment[1], parse_constant=invalid_constant), 'Manifest')
    assets = object_value(site.get('assets', {}), 'assets')
    datasets = object_value(assets.get('data', {}), 'assets.data')

    sources = {manifest}
    outputs = set()
    if 'search' in assets:
        search = object_value(assets['search'], 'assets.search')
        outputs.add(local_path(search.get('output'), manifest.parent, root))
    jobs = []
    for name, config in datasets.items():
        if not name or name != name.strip():
            raise ValueError('Use a nonempty, trimmed source name')
        config = object_value(config, name)
        source = local_path(config.get('source'), manifest.parent, root)
        target = local_path(config.get('output'), manifest.parent, root)
        if target in outputs:
            raise ValueError(f'Multiple assets use the output {target}')
        sources.add(source)
        outputs.add(target)
        kind = str(config.get('type', source.suffix[1:])).strip().lower()
        jobs.append((name, source, target, MIMES.get(kind, kind)))

    for name, source, target, kind in jobs:
        if kind in ('yaml', 'yml'):
            continue
        if kind not in ('csv', 'json'):
            raise ValueError(f'{name}: this command supports CSV and JSON')
        if target in sources or target.suffix.lower() != '.js':
            raise ValueError(f'{name}: use a separate .js output path')
        prefix = (HEADER + 'Object.defineProperty(window.DocFormData || (window.DocFormData = Object.create(null)), '
                  + json.dumps(name, ensure_ascii=False) + ', { configurable: true, enumerable: true, writable: true, value: ')
        existing = target.read_bytes() if target.exists() else None
        if existing is not None and not existing.startswith(prefix.encode('utf-8')):
            raise ValueError(f'{name}: output is not a generated wrapper for this dataset: {target}')
        try:
            data = wrapper(name, source, target, kind, root, prefix)
        except (OSError, ValueError, csv.Error) as error:
            raise ValueError(f'{name} ({source}): {error}') from error
        yield target, data, data != existing


def replace(target, data):
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as pending:
        staged = Path(pending.name)
        try:
            pending.write(data)
            pending.close()
            os.replace(staged, target)
        finally:
            staged.unlink(missing_ok=True)


def refresh(manifest, *, site_root=None):
    try:
        manifest = Path(manifest).resolve()
        root = Path(site_root).resolve() if site_root is not None else manifest.parent
        if not manifest.is_relative_to(root):
            raise ValueError('The manifest must be inside the site folder')
        updates = list(changes(manifest, root))
        for target, data, changed in updates:
            if changed:
                replace(target, data)
            status = 'Updated' if changed else 'Current'
            print(f'{status}: {target.relative_to(root)}')
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0
