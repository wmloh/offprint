  function sameURL(a, b) {
    if (!a || !b) return false;
    try {
      var first = new URL(a);
      var second = new URL(b);
      first.hash = second.hash = first.search = second.search = '';
      return first.href === second.href;
    } catch (error) { return false; }
  }

  function wrappedAsset(kind, name, source) {
    var text = source.replace(/^\s*\/\/ Generated by OffPrint tools\/assets\.html\.[^\S\r\n]*\r?\n/, '').trim();
    if (kind === 'search') {
      var search = /^window\.OffPrintSearch\s*=\s*([\s\S]+);$/.exec(text);
      if (search) return JSON.parse(search[1]);
    } else {
      var data = /^Object\.defineProperty\(window\.OffPrintData \|\| \(window\.OffPrintData = Object\.create\(null\)\), ("(?:[^"\\]|\\.)*"), \{ configurable: true, enumerable: true, writable: true, value: ([\s\S]+) \}\);$/.exec(text);
      if (data && JSON.parse(data[1]) === name) return JSON.parse(data[2]);
    }
    throw new Error('Unsupported OffPrint asset wrapper.');
  }

  function issue(issues, code, node, message) {
    issues.push({ code: code, target: node?.id || node?.getAttribute('src') || node?.localName || null, message: message });
  }

  function fallback(node, issues, code) {
    var label = node.getAttribute('aria-label') || node.getAttribute('title') || node.getAttribute('alt');
    var replacement = node.ownerDocument.createElement('div');
    if (node.id) replacement.id = node.id;
    if (node.matches('object,canvas')) replacement.append(...node.childNodes);
    if (!replacement.textContent.trim() && !replacement.querySelector('img,svg')) {
      replacement.append(label || 'Embedded content is unavailable in this snapshot.');
    }
    issue(issues, code, node, 'Embedded content uses a static fallback.');
    node.replaceWith(replacement);
  }

  function showStaticFallbacks(scope) {
    scope.querySelectorAll('noscript').forEach(function (node) {
      var owner = node.ownerDocument;
      var content = owner.createElement('div');
      if (node.children.length) content.append(...node.childNodes);
      else {
        var template = owner.createElement('template');
        template.innerHTML = node.textContent;
        content.append(template.content);
      }
      if (node.id) content.id = node.id;
      node.replaceWith(content);
    });
  }

  function neutralize(scope) {
    var nodes = Array.from(scope.querySelectorAll('*'));
    if (scope.nodeType === 1) nodes.unshift(scope);
    nodes.forEach(function (node) {
      Array.from(node.attributes).forEach(function (attr) {
        if (/^on/i.test(attr.name) || ['autofocus', 'autoplay', 'ping'].includes(attr.name) ||
            /^(?:href|xlink:href|src|action|formaction)$/i.test(attr.name) &&
            /^\s*javascript:/i.test(attr.value.replace(/[\t\r\n]/g, ''))) {
          node.removeAttribute(attr.name);
        }
      });
    });
  }

  function staticControl(node, document, original) {
    original = original || node;
    var tag = node.localName;
    var copy = document.createElement(tag === 'textarea' ? 'pre' : 'span');
    Array.from(node.attributes).forEach(function (attr) {
      if (/^(?:id|class|style|title|aria-describedby|aria-label|data-op-.+)$/.test(attr.name)) {
        copy.setAttribute(attr.name, attr.value);
      }
    });
    if (tag === 'button') {
      copy.append(...node.childNodes);
      if (node.getAttribute('aria-selected') === 'true' || node.getAttribute('aria-pressed') === 'true') {
        copy.setAttribute('data-op-snapshot-selected', '');
      }
      if (node.hasAttribute('aria-current')) copy.setAttribute('aria-current', node.getAttribute('aria-current'));
    } else if (tag === 'select') {
      copy.textContent = Array.from(original.selectedOptions, function (option) { return option.label; }).join(', ');
    } else if (node.type === 'checkbox' || node.type === 'radio') {
      if (!node.closest('.op-chip')) {
        copy.textContent = (original.checked ? '☑' : '☐') + ' ' + (node.getAttribute('aria-label') || '');
      }
    } else if (['file', 'password', 'hidden'].includes(node.type)) {
      node.remove();
      return;
    } else {
      copy.textContent = node.closest('.op-param') ? original.value : original.defaultValue;
    }
    if (copy.childNodes.length) node.replaceWith(copy);
    else node.remove();
  }

