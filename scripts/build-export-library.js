'use strict';

const fs = require('node:fs');
const path = require('node:path');

const library = path.join(__dirname, '../docform');
const output = path.join(library, 'js/export-library.js');
const runtimeOutput = path.join(library, 'js/export-runtime.js');
const katex = 'vendor/katex';

function filesIn(directory, extension) {
  return fs.readdirSync(path.join(library, directory), { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith(extension))
    .map(entry => directory + '/' + entry.name)
    .sort();
}

function bundleSource() {
  const katexCSS = katex + '/katex.min.css';
  const styles = Object.fromEntries(['docform.css', ...filesIn('css', '.css'), katexCSS]
    .map(relative => [relative, fs.readFileSync(path.join(library, relative), 'utf8')]));
  // The offline library ships only the WOFF2 variants.
  styles[katexCSS] = styles[katexCSS].replace(/,url\(fonts\/[^)]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, '');

  const fonts = Object.fromEntries(filesIn(katex + '/fonts', '.woff2')
    .map(relative => [relative, fs.readFileSync(path.join(library, relative)).toString('base64')]));

  return '// Generated by node scripts/build-export-library.js. KaTeX license: vendor/katex/LICENSE.\n' +
    '(function (root) {\n' +
    "  'use strict';\n" +
    '  root.DocForm._exportLibrary = ' + JSON.stringify({ styles, fonts }, null, 2).replaceAll('\n', '\n  ') + ';\n' +
    '})(window);\n';
}

function isCurrent() {
  return outputs().every(([file, content]) => matches(file, content));
}

function matches(file, content) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content;
}

function outputs() {
  const modules = ['docform.js', ...filesIn('js', '.js').filter(file => !/^js\/(?:export-|page-snapshot\.js)/.test(file)),
    katex + '/katex.min.js', 'vendor/js-yaml/js-yaml.min.js'];
  const scripts = Object.fromEntries(modules.map(file => [file, fs.readFileSync(path.join(library, file), 'utf8')]));
  const runtime = '// Generated by node scripts/build-export-library.js. Vendor licenses are under vendor/.\n' +
    '(function (root) {\n' +
    "  'use strict';\n" +
    '  root.DocForm._exportRuntime = ' + JSON.stringify(scripts, null, 2).replaceAll('\n', '\n  ') + ';\n' +
    '})(window);\n';
  return [[output, bundleSource()], [runtimeOutput, runtime]];
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!isCurrent()) {
      console.error('The DocForm export library is out of date. Run node scripts/build-export-library.js.');
      process.exitCode = 1;
    }
  } else {
    for (const [file, content] of outputs()) {
      if (!matches(file, content)) fs.writeFileSync(file, content);
    }
  }
}

module.exports = { isCurrent };
